insert into TB_TBL_IDX(IDX_SN, PRJ_SN, TBL_SN, IDX_NM, IDX_TYPE_NM, UNQ_YN, APRV_YN, IDX_SRC_CD, DRVN_COL_SN, REG_DT, MDFCN_DT, RGTR_ID, MDFR_ID)
select nextval('SQ_TBL_IDX'), 0, t.TBL_SN, s.IDX_NM, null, s.UNQ_YN, true, 'USER', null, current_timestamp, current_timestamp, 'SYSTEM', 'SYSTEM'
from (select distinct TBL_NM, IDX_NM, UNQ_YN from TMP_IDX_SEED) s
join TB_TBL t on t.PRJ_SN = 0 and t.TBL_NM = s.TBL_NM
where not exists (select 1 from TB_TBL_IDX i where i.TBL_SN = t.TBL_SN and i.IDX_NM = s.IDX_NM)
  and (select count(*) from TMP_IDX_SEED x join TB_COL c on c.TBL_SN = t.TBL_SN and c.COL_NM = x.COL_NM where x.IDX_NM = s.IDX_NM)
    = (select count(*) from TMP_IDX_SEED x where x.IDX_NM = s.IDX_NM);
-- 위에서 만든 인덱스만 (컬럼이 아직 없는 것)
insert into TB_TBL_IDX_COL(IDX_COL_SN, IDX_SN, COL_SN, COL_ORD)
select nextval('SQ_TBL_IDX_COL'), i.IDX_SN, c.COL_SN, s.COL_ORD
from TMP_IDX_SEED s
join TB_TBL t on t.PRJ_SN = 0 and t.TBL_NM = s.TBL_NM
join TB_TBL_IDX i on i.TBL_SN = t.TBL_SN and i.IDX_NM = s.IDX_NM
join TB_COL c on c.TBL_SN = t.TBL_SN and c.COL_NM = s.COL_NM
where not exists (select 1 from TB_TBL_IDX_COL x where x.IDX_SN = i.IDX_SN);

