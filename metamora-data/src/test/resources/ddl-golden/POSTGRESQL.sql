-- PostgreSQL DDL : TB_ORDER (주문)
CREATE TABLE TB_ORDER (
    ORDER_NO  BIGINT NOT NULL,
    USER_ID   VARCHAR(30) NOT NULL,
    STAT_CD   VARCHAR(10),
    DEPT_ID   NUMERIC(10),
    ETC_ID    NUMERIC,
    PARENT_NO BIGINT,
    ORDER_DT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EMAIL     VARCHAR,
    AMT       NUMERIC(12,2) DEFAULT 0,
    MEMO      TEXT,
    CONSTRAINT PK_TB_ORDER PRIMARY KEY (ORDER_NO),
    CONSTRAINT UK_TB_ORDER_EMAIL UNIQUE (EMAIL)
);

CREATE INDEX IX_TB_ORDER_STAT_CD ON TB_ORDER (STAT_CD);
CREATE INDEX IX_TB_ORDER_ORDER_DT ON TB_ORDER (ORDER_DT);

ALTER TABLE TB_ORDER ADD CONSTRAINT FK_TB_ORDER_USER_ID FOREIGN KEY (USER_ID) REFERENCES TB_USER (USER_ID);
ALTER TABLE TB_ORDER ADD CONSTRAINT FK_TB_ORDER_PARENT_NO FOREIGN KEY (PARENT_NO) REFERENCES TB_ORDER (ORDER_NO);

COMMENT ON TABLE TB_ORDER IS '주문';
COMMENT ON COLUMN TB_ORDER.ORDER_NO IS '주문 번호';
COMMENT ON COLUMN TB_ORDER.USER_ID IS '주문자';
COMMENT ON COLUMN TB_ORDER.STAT_CD IS '상태 코드';
COMMENT ON COLUMN TB_ORDER.DEPT_ID IS '부서';
COMMENT ON COLUMN TB_ORDER.PARENT_NO IS '상위 주문';
COMMENT ON COLUMN TB_ORDER.ORDER_DT IS '주문 일시';
COMMENT ON COLUMN TB_ORDER.AMT IS '금액''s';

-- warnings
EMAIL : 최대 길이가 없어 길이 없는 VARCHAR 로 생성했습니다.
USER_ID : 참조 PK 와 길이/정밀도가 다릅니다. 값이 들어가지 않거나 잘리지 않도록 맞추는 것을 권장합니다. (USER_ID VARCHAR(30) ↔ TB_USER.USER_ID VARCHAR(20))
STAT_CD : 참조 테이블 TB_CODE 의 PK 가 복합키(GRP_CD, CD)라 FK 를 만들지 않았습니다.
DEPT_ID : 참조 테이블 TB_DEPT 에 PK 가 없어 FK 를 만들지 않았습니다.
ETC_ID : 참조 테이블 TB_NONE 이(가) 테이블 관리에 등록되어 있지 않아 FK 를 만들지 않았습니다.